#!/usr/bin/env python3
"""Build a TAKT runtime.yaml from the shared role table and one environment.

    build-runtime.py --env work [--deny opencode --deny openrouter] [-o PATH]

Inputs (next to this script):
  common/targets.yaml   which role each step / persona plays (shared)
  <env>/profiles.yaml   roles -> provider/model, plus optional named
                        assignments that override some roles

Output: a runtime.yaml whose profiles are the role names. A named assignment
`X` gets profiles `<role>@X` for the roles it overrides and a full copy of the
targets pointing at them (TAKT replaces defaults/targets wholesale when an
assignment is selected).

--deny PROVIDER fails the build if any profile uses that provider or a model
id prefixed with `PROVIDER/` / `PROVIDER-go/`, and also fails on base_url /
API-key options. install.sh uses it for the work environment.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
HEADER = """\
# GENERATED by dotfiles takt/build-runtime.py from takt/common/targets.yaml and
# takt/{env}/profiles.yaml. Do not edit: re-run install.sh instead.
"""


class BuildError(Exception):
    pass


def load(path: Path) -> dict:
    with path.open(encoding="utf-8") as f:
        data = yaml.safe_load(f)
    if not isinstance(data, dict):
        raise BuildError(f"{path}: expected a mapping")
    return data


# Sections of common/targets.yaml that map a name to a role.
TARGET_KINDS = ("personas", "steps", "tags", "internal_agents")


def role_refs(value) -> list[str]:
    if isinstance(value, str):
        return [value]
    if isinstance(value, dict) and set(value) == {"ladder"} and isinstance(value["ladder"], list):
        return list(value["ladder"])
    raise BuildError(f"targets: expected a role name or {{ladder: [...]}}, got {value!r}")


def assignment_entry(value, rename) -> dict:
    if isinstance(value, str):
        return {"profile": rename(value)}
    return {"ladder": [rename(r) for r in value["ladder"]]}


def build_section(targets: dict, rename) -> tuple[dict, dict]:
    defaults = assignment_entry(targets["defaults"], rename)
    out: dict = {}
    for kind in TARGET_KINDS:
        entries = targets.get(kind) or {}
        if entries:
            out[kind] = {name: assignment_entry(v, rename) for name, v in entries.items()}
    return defaults, out


def check_denied(profiles: dict, deny: list[str]) -> None:
    for name, profile in profiles.items():
        provider = str(profile.get("provider", ""))
        model = str(profile.get("model", ""))
        options = profile.get("options") or {}
        for denied in deny:
            if provider == denied or model.startswith((f"{denied}/", f"{denied}-go/")):
                raise BuildError(f"profile {name!r} uses denied provider {denied!r} ({provider} {model})")
        for key in options:
            lowered = str(key).lower()
            if "base_url" in lowered or "api_key" in lowered:
                raise BuildError(f"profile {name!r} sets {key!r}, which is not allowed here")


def build(env: str, deny: list[str], root: Path = HERE) -> str:
    targets = load(root / "common" / "targets.yaml")
    env_file = load(root / env / "profiles.yaml")
    roles = env_file.get("roles")
    if not isinstance(roles, dict) or not roles:
        raise BuildError(f"{env}/profiles.yaml: `roles` is required")
    if "defaults" not in targets:
        raise BuildError("common/targets.yaml: `defaults` is required")

    used = set(role_refs(targets["defaults"]))
    for kind in TARGET_KINDS:
        for name, value in (targets.get(kind) or {}).items():
            if kind == "internal_agents" and not isinstance(value, str):
                raise BuildError(f"targets: internal_agents.{name} takes a role name, not a ladder")
            used.update(role_refs(value))
    missing = sorted(used - set(roles))
    if missing:
        raise BuildError(f"{env}/profiles.yaml: roles not defined: {', '.join(missing)}")

    profiles = {name: dict(spec) for name, spec in roles.items()}
    defaults, section_targets = build_section(targets, lambda r: r)
    provider: dict = {"profiles": profiles, "defaults": defaults, "targets": section_targets}

    assignments = env_file.get("assignments") or {}
    if assignments:
        provider["assignments"] = {}
    for assignment, overrides in assignments.items():
        unknown = sorted(set(overrides) - set(roles))
        if unknown:
            raise BuildError(f"{env}/profiles.yaml: assignment {assignment!r} overrides unknown roles: {', '.join(unknown)}")
        for role, spec in overrides.items():
            profiles[f"{role}@{assignment}"] = dict(spec)

        def rename(role, overrides=overrides, assignment=assignment):
            return f"{role}@{assignment}" if role in overrides else role

        a_defaults, a_targets = build_section(targets, rename)
        provider["assignments"][assignment] = {"defaults": a_defaults, "targets": a_targets}

    check_denied(profiles, deny)
    body = yaml.safe_dump({"version": 1, "provider": provider}, sort_keys=False, allow_unicode=True)
    return HEADER.format(env=env) + body


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--env", required=True, help="environment directory under takt/ (work, private)")
    parser.add_argument("--deny", action="append", default=[], help="provider that must not appear (repeatable)")
    parser.add_argument("-o", "--output", help="write here instead of stdout")
    args = parser.parse_args(argv)
    try:
        text = build(args.env, args.deny)
    except (BuildError, OSError, yaml.YAMLError) as e:
        print(f"build-runtime: {e}", file=sys.stderr)
        return 1
    if args.output:
        Path(args.output).write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
